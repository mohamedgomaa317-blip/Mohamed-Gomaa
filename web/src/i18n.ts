let locale: Locale = 'ar';
export const setLocale = (l: Locale): void => {
  locale = l;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
};
export const getLocale = (): Locale => locale;
export function t(k: Key, vars: Record<string, string | number> = {}): string {
  return (locale === 'ar' ? ar : en)[k].replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? ''));
}
/** Arabic-Indic digits are not used: numbers stay Western for consistency with CEFR codes. */
export const pct = (r: number): string => `${Math.round(r * 100)}%`;
